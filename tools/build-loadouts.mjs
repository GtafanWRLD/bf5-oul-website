// Builds loadouts.js for the Loadout randomizer: per class the sidearms, gadgets, throwables and
// combat roles, and per gun the sights it can use. Everything comes from the Battlefield wiki:
// class pages ({{Infobox/kit}}) and each gun's "All sights" gallery. Guns and their spec trees
// come from weapon-stats.js, so run build-weapon-stats.mjs first.
//
//   node tools/build-loadouts.mjs

import { readFileSync, writeFileSync } from "node:fs";

const WIKI = "https://battlefield.fandom.com/api.php";
const CLASS_PAGES = { Assault: "Assault/Battlefield V", Medic: "Medic/Battlefield V", Support: "Support/Battlefield V", Recon: "Recon/Battlefield V" };
// From the wiki's Combat Role page (two per class).
const ROLES = {
  Assault: ["Light Infantry", "Vehicle Buster"],
  Medic: ["Field Medic", "Combat Medic"],
  Support: ["Engineer", "Machine Gunner"],
  Recon: ["Sniper", "Pathfinder"],
};
// Wiki pages for guns weapon-stats.js has no tree page for.
const PAGES = { EMP: "EMP (submachine gun)", RSC: "RSC 1917", "ZH-29": "ZH-29" };
// Guns with a fixed sight and no "All sights" gallery.
const FIXED_SIGHTS = { "M3 Infrared": ["Infrared Scope (3x, built in)"] };

const cache = new Map();
async function page(title) {
  if (!cache.has(title)) {
    const url = `${WIKI}?${new URLSearchParams({ action: "parse", format: "json", prop: "wikitext", redirects: "1", page: title })}`;
    const j = await (await fetch(url)).json();
    cache.set(title, j.parse?.wikitext?.["*"] || "");
  }
  return cache.get(title);
}

/** "[[Rifle Grenade#Battlefield V|Frag Grenade Rifle]] <small>(Rank 4)</small><br />[[PIAT]]" → names. */
function linkList(field) {
  return field.replace(/<!--[\s\S]*?-->/g, "").split(/<br\s*\/?>/i)
    .map((x) => x.replace(/<small>[\s\S]*?<\/small>/gi, "").match(/\[\[([^\]|]+)(?:\|([^\]]+))?\]\]/))
    .filter(Boolean).map((m) => (m[2] || m[1]).trim());
}

function kitField(text, name) {
  const m = text.match(new RegExp(`\\|\\s*${name}\\s*=([^\\n]*)`));
  return m ? linkList(m[1]) : [];
}

/**
 * Sight names from "All [[Sights/Battlefield V|sights]]" galleries ("File.png|Nydar Sight").
 * Shared pages (M1 Carbine, Sturmgewehr 1-5) have one gallery per gun under its own heading, so
 * take the gallery in the section whose heading names the gun, else the first.
 */
function sightsOf(text, gun) {
  const galleries = [];
  // The gallery is either plain or inside a <tabber> with one tab per variant (Default, Bayonet…).
  const re = /All \[\[Sights\/Battlefield V\|sights\]\][^\n]*\n(<tabber>[\s\S]*?<\/tabber>|<gallery[^>]*>[\s\S]*?<\/gallery>)/gi;
  for (let m; (m = re.exec(text)); ) {
    const before = text.slice(0, m.index);
    const heading = [...before.matchAll(/^=+\s*(.+?)\s*=+\s*$/gm)].map((h) => h[1]).filter((h) => !/gallery|sights|skins|visuals/i.test(h)).at(-1) || "";
    const names = m[1].split("\n").filter((l) => /\.(png|jpe?g)\|/i.test(l)).map((l) => l.split("|")[1]?.trim()).filter(Boolean)
      .map((n) => n.replace(/\s*\(.*\)$/, "")).filter((n, i, a) => a.indexOf(n) === i);
    galleries.push({ heading, names });
  }
  const norm = (x) => x.toLowerCase().replace(/[^a-z0-9]/g, "");
  return (galleries.find((g) => norm(g.heading).includes(norm(gun)) || norm(gun).includes(norm(g.heading)) && g.heading) || galleries[0])?.names || [];
}

const window = {};
new Function("window", readFileSync("weapon-stats.js", "utf8"))(window);
const weapons = window.WEAPON_STATS.weapons;

const classes = {};
for (const [cls, title] of Object.entries(CLASS_PAGES)) {
  const text = await page(title);
  classes[cls] = {
    roles: ROLES[cls],
    sidearms: kitField(text, "weapon2"),
    gadget1: kitField(text, "gadget1"),
    gadget2: kitField(text, "gadget2"),
    throwables: kitField(text, "equip1"),
  };
}

const sights = {};
for (const w of weapons.filter((w) => w.cls !== "Sidearm")) {
  const list = FIXED_SIGHTS[w.name] || sightsOf(await page(PAGES[w.name] || w.treeSource || w.name), w.name);
  if (list.length) sights[w.name] = list;
}

const missing = weapons.filter((w) => w.cls !== "Sidearm" && !sights[w.name]).map((w) => w.name);
const known = new Set(weapons.map((w) => w.name));
const unknownSidearms = [...new Set(Object.values(classes).flatMap((c) => c.sidearms))].filter((n) => !known.has(n));
console.log(JSON.stringify(classes, null, 1));
console.log("guns with sights:", Object.keys(sights).length, "missing:", missing.join(", ") || "none");
console.log("sidearms not in weapon-stats:", unknownSidearms.join(", ") || "none");

writeFileSync("loadouts.js", `// Generated by tools/build-loadouts.mjs from the Battlefield wiki. Used by the Loadout randomizer.
window.LOADOUTS = ${JSON.stringify({ builtAt: new Date().toISOString(), classes, sights })};
`);
