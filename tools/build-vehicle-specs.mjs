// Builds vehicle-specs.js: BFV vehicle specialization trees for the Vehicle upgrades tab.
//
// Source: the Battlefield wiki's "Vehicle Specializations" page (battlefield.fandom.com), the only
// public list of every vehicle's upgrades. No public source has vehicle numbers (health, shell
// damage, speed), so the tab shows the trees and what each upgrade does, nothing invented.
// The wiki has 6-tier trees for the Pacific vehicles but only 4 tiers for the European ones, so
// those are flagged as possibly outdated.
//
//   node tools/build-vehicle-specs.mjs

import { writeFileSync } from "node:fs";

const PAGE = "Specializations (Battlefield V)/Vehicles";
const url = `https://battlefield.fandom.com/api.php?${new URLSearchParams({ action: "parse", page: PAGE, prop: "wikitext", format: "json", redirects: "1" })}`;
const text = (await (await fetch(url, { headers: { "User-Agent": "bf5-tools" }, signal: AbortSignal.timeout(60000) })).json()).parse.wikitext["*"];

globalThis.window = {};
await import(new URL("../catalog.js", import.meta.url));
const key = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
const catalog = new Map(window.CATALOG.vehicles.map((v) => [key(v.name), v]));
/** Wiki name → catalog (gametools) name where they differ. */
const CATALOG_NAMES = { "StuG IV": "Sturmgeschutz iv" };

const link = (s) => s.replace(/\[\[[^\]|]*\|([^\]]+)\]\]/g, "$1").replace(/\[\[([^\]]+)\]\]/g, "$1");
const clean = (s) => link(s).replace(/''/g, "").replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();

const vehicles = [];
let faction = "";
for (const section of text.split(/\n(?====[^=])|\n(?=\|-\|)/)) {
  const tab = section.match(/^\|-\|\s*(.+?)\s*=/);
  if (tab) { faction = tab[1]; continue; }
  const head = section.match(/^===\s*(.+?)\s*===/);
  if (!head) continue;
  const name = link(head[1]).trim();
  const specs = [];
  for (const row of section.split(/\n\|-\n/).slice(2)) {
    const cells = row.split("\n").filter((l) => l.startsWith("|") && !l.startsWith("|}")).map((l) => l.slice(1).trim());
    if (cells.length < 4) continue;
    const tier = parseInt(clean(cells[3]), 10);
    if (tier) specs.push({ name: clean(cells[0]), desc: clean(cells[2]), tier });
  }
  if (!specs.length) continue;
  const depth = Math.max(...specs.map((s) => s.tier));
  // [[{ name, desc }]] per tier, in the wiki's order.
  const tree = Array.from({ length: depth }, (_, i) => specs.filter((s) => s.tier === i + 1).map(({ name, desc }) => ({ name, desc })));
  const cat = catalog.get(key(CATALOG_NAMES[name] || name));
  vehicles.push({ name, faction, type: cat?.type || null, image: cat?.image || null, tree, outdated: depth < 6 });
}

// Tanks and planes the wiki doesn't list: shown, marked as having no upgrade data. The C-47 is a
// transport with no upgrades in game.
const listed = new Set(vehicles.map((v) => key(CATALOG_NAMES[v.name] || v.name)));
for (const v of window.CATALOG.vehicles) {
  if (!["Tanks", "Planes"].includes(v.type) || listed.has(key(v.name)) || key(v.name) === "c47") continue;
  vehicles.push({ name: v.name.replace(/\b([a-z])/g, (c) => c.toUpperCase()), faction: null, type: v.type, image: v.image, tree: [], outdated: false });
}
vehicles.sort((a, b) => a.name.localeCompare(b.name));

const noImage = vehicles.filter((v) => !v.image).map((v) => v.name);
if (noImage.length) console.warn("No image:", noImage.join(", "));
writeFileSync(
  new URL("../vehicle-specs.js", import.meta.url),
  `// Generated by tools/build-vehicle-specs.mjs from the Battlefield wiki. Used by the Vehicle upgrades tab.\n` +
    `window.VEHICLE_SPECS = ${JSON.stringify({ builtAt: new Date().toISOString(), source: `https://battlefield.fandom.com/wiki/${PAGE.replace(/ /g, "_")}`, vehicles })};\n`,
);
const withTree = vehicles.filter((v) => v.tree.length);
console.log(`vehicle-specs.js: ${withTree.length} vehicles with trees (${withTree.filter((v) => v.outdated).length} possibly outdated), ${vehicles.length - withTree.length} without data`);
