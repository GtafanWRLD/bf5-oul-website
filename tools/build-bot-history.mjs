// Builds bot-history.js for the Player lookup tab from the Discord bot's data/store.json: every
// name the bot has seen per player and where it last saw them. The bot's Discord account links
// are left out.
//
//   node tools/build-bot-history.mjs <path-to-store.json>
//   (defaults to ../Bf Bot/data/store.json)

import { readFileSync, writeFileSync } from "node:fs";

const file = process.argv[2] || "../Bf Bot/data/store.json";
const store = JSON.parse(readFileSync(file, "utf8"));
const sec = (ms) => Math.round(ms / 1000);

// id → [names, lastSeenAt, lastSeenServer]; names are [name, firstSeen, lastSeen] oldest first.
const players = {};
for (const [id, entries] of Object.entries(store.names || {})) {
  const names = [...entries].sort((a, b) => a.firstSeen - b.firstSeen).map((e) => [e.name, sec(e.firstSeen), sec(e.lastSeen)]);
  const seen = store.seen?.[id];
  players[id] = seen ? [names, sec(seen.at), seen.server] : [names];
}

const latest = Math.max(0, ...Object.values(store.seen || {}).map((s) => s.at));
writeFileSync("bot-history.js", `// Generated by tools/build-bot-history.mjs from the Discord bot's store. Used by Player lookup.
window.BOT_HISTORY = ${JSON.stringify({ builtAt: new Date().toISOString(), dataUntil: latest ? new Date(latest).toISOString() : null, players })};
`);
const renamed = Object.values(players).filter((p) => p[0].length > 1).length;
console.log(`${Object.keys(players).length} players, ${renamed} with more than one name, data until ${latest ? new Date(latest).toISOString() : "?"}`);
